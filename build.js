// Bundles each src/providers/<id>.js into a single CommonJS file at providers/<id>.js,
// which is what Nuvio downloads and evaluates.
const esbuild = require('esbuild');
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, 'src', 'providers');
const OUT = path.join(__dirname, 'providers');

const only = process.argv.slice(2);
const ids = fs
  .readdirSync(SRC)
  .filter((f) => f.endsWith('.js'))
  .map((f) => f.replace(/\.js$/, ''))
  .filter((id) => !only.length || only.includes(id));

fs.mkdirSync(OUT, { recursive: true });

for (const id of ids) {
  esbuild.buildSync({
    entryPoints: [path.join(SRC, id + '.js')],
    outfile: path.join(OUT, id + '.js'),
    bundle: true,
    format: 'cjs',
    platform: 'neutral',
    target: 'es2020',
    // Nuvio provides cheerio natively through require()
    external: ['cheerio-without-node-native'],
    legalComments: 'none',
    banner: { js: '// ' + id + ' — generated by build.js from src/providers/' + id + '.js; do not edit' },
  });
  console.log('built providers/' + id + '.js');
}
